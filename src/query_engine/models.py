from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class IntentType(str, Enum):
    AGGREGATION = "aggregation"            # Total sum/volume/count for product/company/period
    RANKING = "ranking"                    # Top sellers, buyers, products, brokers, regions
    PRICE_INQUIRY = "price_inquiry"        # Avg, min, max price of a commodity
    DEAL_LOOKUP = "deal_lookup"            # Information about a specific deal by ID
    CONTRACT_LOOKUP = "contract_lookup"    # Information about a specific contract by ID
    PARTICIPANT_LOOKUP = "participant_lookup" # Company details and stats by INN or name
    BROKER_LOOKUP = "broker_lookup"        # Broker info and stats by code or name
    USD_RATE_LOOKUP = "usd_rate_lookup"    # USD exchange rate on specific date or range
    STATUS_BREAKDOWN = "status_breakdown"  # Deal count/volume broken down by status
    PERIOD_COMPARISON = "period_comparison"# Compare metrics between two timeframes
    EXCHANGE_INFO = "exchange_info"        # General information about UZEX exchange, bot capabilities, FAQ
    OUT_OF_SCOPE = "out_of_scope"          # Outside dataset date range or unrelated topic
    TEXT_TO_SQL = "text_to_sql"            # Read-only verified SQL generated by AI
    UNKNOWN = "unknown"                    # Unrecognized request


class StatusPolicy(str, Enum):
    """
    Explicit status inclusion policy to prevent mixing active, cancelled, or executed deals:
    - REGISTERED: all 8 statuses (total historical registry)
    - NON_CANCELLED: status != 'Аннулирован(Не оплачен)' (default for active trade turnover)
    - EXECUTED: status = 'Исполнен' (fully delivered & paid)
    - PARTIALLY_EXECUTED: status = 'Исполнен(Частично)'
    - CANCELLED: status = 'Аннулирован(Не оплачен)'
    """
    REGISTERED = "registered"
    NON_CANCELLED = "non_cancelled"
    EXECUTED = "executed"
    PARTIALLY_EXECUTED = "partially_executed"
    CANCELLED = "cancelled"


class VolumeType(str, Enum):
    """
    Distinguishes contracted volume vs actual physically delivered volume:
    - CONTRACTED: quantity * lot (deals.volume)
    - DELIVERED: delivered_qty * lot (deals.delivered_volume)
    """
    CONTRACTED = "contracted"
    DELIVERED = "delivered"


class EntityType(str, Enum):
    PRODUCT = "product"
    SELLER = "seller"
    BUYER = "buyer"
    BROKER = "broker"
    REGION = "region"


class PriceMetrics(BaseModel):
    weighted_avg_price: Optional[float] = None
    simple_avg_price: Optional[float] = None
    min_price: Optional[float] = None
    max_price: Optional[float] = None
    avg_start_price: Optional[float] = None
    unit: Optional[str] = None
    total_volume: float = 0.0
    total_amount_uzs: float = 0.0
    deal_count: int = 0


class TurnoverResult(BaseModel):
    total_amount_uzs: float = 0.0
    total_volume: float = 0.0
    volume_type: VolumeType = VolumeType.CONTRACTED
    status_policy: StatusPolicy = StatusPolicy.NON_CANCELLED
    deal_count: int = 0
    avg_price_uzs: Optional[float] = None
    unit: Optional[str] = None


class ComparisonResult(BaseModel):
    period1_name: str
    period2_name: str
    metric: str
    period1_value: float
    period2_value: float
    absolute_change: float
    percentage_change: Optional[float] = None


class QueryParams(BaseModel):
    intent: IntentType = IntentType.UNKNOWN
    product: Optional[str] = None          # Resolved/canonical product keyword (e.g. 'бензин')
    product_raw: Optional[str] = None      # Exact term from prompt
    category: Optional[str] = None         # Product category from catalog
    year: Optional[int] = None             # 2022..2026
    date_from: Optional[str] = None        # YYYY-MM-DD
    date_to: Optional[str] = None          # YYYY-MM-DD
    inn: Optional[str] = None              # 9-digit participant INN
    participant_name: Optional[str] = None
    role: Optional[str] = None             # 'seller' or 'buyer'
    broker_code: Optional[str] = None      # e.g. 'BK001'
    broker_name: Optional[str] = None
    contract_id: Optional[str] = None      # e.g. '100034'
    deal_id: Optional[int] = None          # e.g. 100001
    deal_status: Optional[str] = None      # Exact status if explicitly queried
    status_policy: StatusPolicy = StatusPolicy.NON_CANCELLED  # Default to active turnover
    volume_type: VolumeType = VolumeType.CONTRACTED          # Default to contracted volume
    contract_type: Optional[str] = None    # 'Внутренний' or 'Экспортный'
    currency: Optional[str] = None         # 'UZS' or 'USD'
    metric: Optional[str] = "amount_uzs"   # 'amount_uzs', 'volume', 'deals_count', 'price'
    ranking_entity: Optional[str] = "product" # 'product', 'seller', 'buyer', 'broker', 'region'
    limit: int = 5
    language: str = "ru"                   # 'ru' or 'uz'


class QueryResult(BaseModel):
    success: bool = True
    has_data: bool = True
    is_out_of_dataset: bool = False
    out_of_dataset_reason: Optional[str] = None
    total_count: int = 0
    total_volume: Optional[float] = None
    total_amount_uzs: Optional[float] = None
    total_amount_usd: Optional[float] = None
    unit: Optional[str] = None
    avg_price: Optional[float] = None
    min_price: Optional[float] = None
    max_price: Optional[float] = None
    currency: Optional[str] = "UZS"
    rows: List[Dict[str, Any]] = Field(default_factory=list)
    sql_executed: Optional[str] = None
    execution_time_ms: float = 0.0
    summary_data: Dict[str, Any] = Field(default_factory=dict)
